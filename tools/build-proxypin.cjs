"use strict";
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const check = process.argv.includes("--check");
assert(process.argv.slice(2).every(arg => arg === "--check"), "Usage: node tools/build-proxypin.cjs [--check]");
const read = filename => fs.readFileSync(path.join(root, filename), "utf8").trimEnd();
const adapter = read("lib/proxypin-adapter.js");
const banner = "/* Generated by tools/build-proxypin.cjs. Edit sources, then rebuild. */\n";
function wrap(source, parameters) {
  return "function g1ProxyPinRun(" + parameters + ") {\n" +
    "  var result;\n  function $done(value) { result = value; }\n" + source +
    "\n  return result;\n}\n";
}
const responseScript = banner + adapter + "\n\n" + wrap(read("g1-acq.js"), "$request, $response, $persistentStore") + `
async function onRequest(context, request) {
  return request;
}

async function onResponse(context, request, response) {
  if (!request || !g1ProxyPinIsGoogleOne(request.url) || g1ProxyPinIsReport(request.url)) return response;
  var store = await g1ProxyPinOpenStore();
  try {
    var result = g1ProxyPinRun(request, response, store);
    if (result && typeof result.body === "string") {
      response.body = result.body;
      // ProxyPin decoded the body before this hook and re-encodes it afterwards.
      g1ProxyPinRemoveHeader(response.headers, "content-encoding");
      g1ProxyPinRemoveHeader(response.headers, "content-length");
    }
  } catch (error) {
    console.log("[g1-proxypin] execution failed; original response retained");
  }
  return response;
}
`;
const reportSource = read("g1-sku-report.js")
  .replaceAll("Shadowrocket", "ProxyPin")
  .replaceAll("小火箭", "ProxyPin")
  .replace("本机脚本已接管 · ", "本机脚本已接管 · ProxyPin · g1-proxypin-v1.0.0 · ");
const reportScript = banner + adapter + "\n\n" + wrap(reportSource, "$request, $persistentStore") + `
async function onRequest(context, request) {
  if (!request || !g1ProxyPinIsReport(request.url)) return g1ProxyPinLocalError(context, 404);
  var store = await g1ProxyPinOpenStore();
  try {
    var result = g1ProxyPinRun(request, store);
    if (!result || !result.response) return g1ProxyPinLocalError(context, 503);
    return {
      scriptContext: context,
      statusCode: result.response.status,
      headers: Object.assign({}, result.response.headers, { "X-G1-ProxyPin-Version": G1_PROXY_PIN_VERSION }),
      body: result.response.body
    };
  } catch (error) {
    console.log("[g1-proxypin] local report failed; no upstream request made");
    return g1ProxyPinLocalError(context, 503);
  }
}
`;
// ProxyPin's script URL matcher receives domainPath, whereas Request Mapping
// matches the complete request URL. Both are additionally checked by the JS.
const scripts = [{ enabled: true, name: "G1 ACQ ProxyPin v1.0.0", url: "^one\\.google\\.com/", script: responseScript }];
const maps = [{ enabled: true, name: "G1 SKU Report ProxyPin v1.0.0", type: "script",
  url: "^https://one\\.google\\.com/g1-sku-report[/]{0,1}([?]*|)$",
  item: { script: reportScript } }];
const outputs = {
  "proxypin/g1-acq-proxypin.js": responseScript,
  "proxypin/g1-report-proxypin.js": reportScript,
  "proxypin/g1-scripts.json": JSON.stringify(scripts, null, 2) + "\n",
  "proxypin/g1-request-map.json": JSON.stringify(maps, null, 2) + "\n"
};
for (const [filename, content] of Object.entries(outputs)) {
  const destination = path.join(root, filename);
  if (check) assert.equal(fs.readFileSync(destination, "utf8"), content, filename + " is stale; run node tools/build-proxypin.cjs");
  else { fs.mkdirSync(path.dirname(destination), { recursive: true }); fs.writeFileSync(destination, content); }
  console.log((check ? "Verified " : "Generated ") + filename);
}
